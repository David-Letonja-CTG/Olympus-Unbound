// Writes the gods' head positions per frame (anchors/<god>_body.json, from flare_render.py) into the client's
// content, for the crowns (spec: god-appearance / boss trophies). Run by render-all.mjs; also on its own:
//
//   node art/blender/heads.mjs
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../client/src/content/heads.ts");
const heads = {};
for (const god of ["zeus", "hades", "poseidon", "athena"]) {
  const file = join(here, "anchors", `${god}_body.json`);
  if (existsSync(file)) heads[`${god}_body`] = JSON.parse(readFileSync(file, "utf8"));
}
const lines = Object.entries(heads).map(
  ([key, points]) => `  ${key}: [${points.map((p) => (p ? `[${p[0]}, ${p[1]}]` : "null")).join(", ")}],`,
);
writeFileSync(
  out,
  `// Generated by art/blender/heads.mjs from the renders' head anchors: do not edit.\n` +
    `/** Top of the head per frame of a god's run figure, 0–1 from the frame's top left (null: none). */\n` +
    `export const HEADS: Readonly<Record<string, readonly (readonly [number, number] | null)[]>> = {\n` +
    `${lines.join("\n")}\n};\n`,
);
console.log(`${out}: ${Object.keys(heads).length} figures`);
