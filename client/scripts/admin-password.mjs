// Sets the admin screen's password (spec: run-statistics / admin mode): stores only its SHA-256 hash.
// Usage: node scripts/admin-password.mjs "<new password>"
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';

const password = process.argv[2];
if (!password || password.length < 12) {
  console.error(
    'Give a password of at least 12 characters: node scripts/admin-password.mjs "<password>"',
  );
  process.exit(1);
}
const hash = createHash('sha256').update(password, 'utf8').digest('hex');
const file = new URL('../src/app/features/admin/admin-password.ts', import.meta.url);
writeFileSync(
  file,
  `// Generated by scripts/admin-password.mjs. Only the hash is stored; the password is never committed.\n` +
    `export const ADMIN_PASSWORD_SHA256 = '${hash}';\n`,
);
console.log('Admin password updated.');
